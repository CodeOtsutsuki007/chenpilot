import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { describe, it } from "node:test";
import {
  checkGeneratedFiles,
  classify,
} from "../../scripts/repo/check-generated-files.mjs";
import { readRepoConfig } from "../../scripts/repo/config.mjs";
import { REPO_ROOT, makeFixture, removeFixture } from "../docs/helpers.mjs";

const config = readRepoConfig(REPO_ROOT).generatedFiles;
const gitignore = fs.readFileSync(path.join(REPO_ROOT, ".gitignore"), "utf8");

function verdict(file, present = [file], marked = []) {
  return classify(file, config, {
    present: new Set(present),
    isMarked: (f) => marked.includes(f),
  });
}

/** A git fixture; `forced` files are added with `git add -f` as if committed past .gitignore. */
function withRepo(files, forced, fn) {
  const dir = makeFixture(files, { git: true });
  try {
    execFileSync("git", ["add", "-f", "--", ...forced], { cwd: dir });
    return fn(dir);
  } finally {
    removeFixture(dir);
  }
}

describe("generated file inventory", () => {
  it("passes on the repository", () => {
    assert.deepEqual(checkGeneratedFiles(REPO_ROOT, config), []);
  });

  it("treats authored JavaScript and hand-written declarations as authored", () => {
    assert.equal(verdict("server.js"), null);
    assert.equal(verdict("scripts/docs/markdown.mjs"), null);
    assert.equal(verdict("types/express.d.ts"), null);
    // Boundary: authored Markdown next to TypeDoc output is not generated.
    assert.equal(verdict("packages/sdk/docs/MULTI_SIG.md"), null);
  });

  it("allows generated classes only at their allowlisted paths", () => {
    assert.equal(verdict("pnpm-lock.yaml").allowed, true);
    assert.equal(verdict("contracts/Cargo.lock").allowed, true);
    assert.equal(
      verdict("contracts/htlc/test_snapshots/test/test_claim_success.1.json")
        .allowed,
      true
    );
    assert.equal(
      verdict("contracts/snapshots/htlc/v1.0.0.snapshot.json").allowed,
      true
    );
    assert.deepEqual(verdict("packages/bot/package-lock.json"), {
      class: "lockfile",
      allowed: false,
      why: "generated by pnpm install / npm install / cargo",
      remedy:
        "delete it, or add it to generatedFiles.tracked in scripts/repo/repo-check.config.json and the policy",
    });
    assert.equal(verdict("src/fixtures/state.snapshot.json").allowed, false);
  });

  it("never allows build outputs or JavaScript emitted next to its TypeScript", () => {
    assert.equal(
      verdict("packages/sdk/dist/index.js").class,
      "compiled-output"
    );
    assert.equal(
      verdict("contracts/target/release/htlc.wasm").class,
      "contract-build-output"
    );
    assert.equal(verdict("packages/sdk/docs/index.html").class, "typedoc-html");
    assert.equal(
      verdict("chen-pilot-sdk-core-0.1.0.tgz").class,
      "packed-artifact"
    );
    const emitted = verdict("src/services/foo.js", [
      "src/services/foo.js",
      "src/services/foo.ts",
    ]);
    assert.equal(emitted.class, "emitted-from-typescript");
    assert.equal(emitted.allowed, false);
    assert.equal(
      verdict("src/services/foo.d.ts", [
        "src/services/foo.d.ts",
        "src/services/foo.ts",
      ]).class,
      "emitted-from-typescript"
    );
  });

  it("treats a file with a generated marker as generated unless allowlisted", () => {
    assert.equal(
      verdict("src/gen/routes.ts", undefined, ["src/gen/routes.ts"]).allowed,
      false
    );
    assert.equal(
      verdict("docs/TOOLS.md", undefined, ["docs/TOOLS.md"]).allowed,
      true
    );
  });

  it("reports newly tracked generated files and build outputs", () => {
    const files = {
      ".gitignore": gitignore,
      "server.js": "// authored\n",
      "src/app.ts": "export {};\n",
      "src/app.js": "exports.x = 1;\n",
      "src/routes.ts": "// DO NOT EDIT: generated by routegen\nexport {};\n",
      "packages/bot/package-lock.json": "{}\n",
      "dist/index.js": "compiled\n",
    };
    withRepo(files, Object.keys(files), (dir) => {
      assert.deepEqual(checkGeneratedFiles(dir, config), [
        "dist/index.js: compiled-output (build output of tsc (npm run build, npm run build:sdk)) is not allowed in source control; delete it and keep it ignored",
        "dist/index.js: tracked file is matched by .gitignore; narrow the ignore rule",
        "packages/bot/package-lock.json: lockfile (generated by pnpm install / npm install / cargo) is not allowed in source control; delete it, or add it to generatedFiles.tracked in scripts/repo/repo-check.config.json and the policy",
        "src/app.js: emitted-from-typescript (compiled from src/app.ts) is not allowed in source control; delete it and keep it ignored",
        "src/routes.ts: marked-generated (carries a generated-file marker) is not allowed in source control; delete it, or add it to generatedFiles.tracked in scripts/repo/repo-check.config.json and the policy",
      ]);
    });
  });

  it("checks files that are new but not yet added", () => {
    const dir = makeFixture(
      { ".gitignore": gitignore, "src/a.ts": "", "src/a.js": "" },
      { git: true }
    );
    try {
      assert.deepEqual(checkGeneratedFiles(dir, config), [
        "src/a.js: emitted-from-typescript (compiled from src/a.ts) is not allowed in source control; delete it and keep it ignored",
      ]);
    } finally {
      removeFixture(dir);
    }
  });

  it("fails when a blanket ignore rule hides authored files or a build output is not ignored", () => {
    // `*.js` hides authored JavaScript, and dropping `dist/` un-ignores build output.
    const blanket = gitignore.replace(/^dist\/$/m, "") + "\n*.js\n";
    withRepo(
      { ".gitignore": blanket, "server.js": "// authored\n" },
      ["server.js"],
      (dir) => {
        const problems = checkGeneratedFiles(dir, config);
        assert.ok(
          problems.includes(
            "server.js: tracked file is matched by .gitignore; narrow the ignore rule"
          )
        );
        assert.ok(
          problems.includes(
            '.gitignore: compiled-output output "packages/sdk/dist/index.d.ts" is not ignored'
          )
        );
      }
    );
  });
});
